 SELECT p.public_id, CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('core.author_name','legacy.author_name'))=1
   THEN MAX(f.value) FILTER (WHERE f.field_key IN ('core.author_name','legacy.author_name')) END AS author,
CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('core.category','legacy.category'))=1
   THEN MAX(f.value) FILTER (WHERE f.field_key IN ('core.category','legacy.category')) END AS category,
CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('legacy.creation_dynasty_raw'))=1
   THEN MAX(f.value) FILTER (WHERE f.field_key IN ('legacy.creation_dynasty_raw')) END AS dynasty_raw,
CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('legacy.author_birth_place'))=1
   THEN MAX(f.value) FILTER (WHERE f.field_key IN ('legacy.author_birth_place')) END AS birthplace,
CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('legacy.style','annotation.style'))=1
   THEN MAX(f.value) FILTER (WHERE f.field_key IN ('legacy.style','annotation.style')) END AS style,
CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('legacy.artistic_conception'))=1
   THEN MAX(f.value) FILTER (WHERE f.field_key IN ('legacy.artistic_conception')) END AS mood,
CASE WHEN count(DISTINCT f.value) FILTER (WHERE f.field_key IN ('legacy.music_scene_description'))=1
