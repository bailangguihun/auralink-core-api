CREATE FUNCTION community.v2_reaction_to_canonical() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE kind text; pid integer; uid bigint;
BEGIN
 IF pg_trigger_depth()>1 THEN RETURN coalesce(NEW,OLD); END IF;
 kind=CASE WHEN TG_TABLE_NAME='v2_post_likes' THEN 'like' ELSE 'favorite' END;
 pid=CASE WHEN TG_OP='DELETE' THEN OLD.post_id ELSE NEW.post_id END;
 uid=CASE WHEN TG_OP='DELETE' THEN OLD.user_id ELSE NEW.user_id END;
 IF TG_OP='DELETE' THEN DELETE FROM community.reactions r WHERE r.post_id=(SELECT legacy_id FROM community.v2_posts WHERE id=pid) AND r.user_id=uid AND r.kind=kind;
 ELSE INSERT INTO community.reactions(post_id,user_id,kind) VALUES((SELECT legacy_id FROM community.v2_posts WHERE id=pid),uid,kind) ON CONFLICT DO NOTHING; END IF;
 RETURN coalesce(NEW,OLD);
END $$;
