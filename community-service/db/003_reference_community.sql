 INSERT INTO community.v2_tags(name) SELECT unnest(NEW.tags) ON CONFLICT DO NOTHING;
 DELETE FROM community.v2_post_tags WHERE post_id=pid;
 INSERT INTO community.v2_post_tags(post_id,tag_id) SELECT pid,id FROM community.v2_tags WHERE name=ANY(NEW.tags);
 RETURN NEW;
END $$;
