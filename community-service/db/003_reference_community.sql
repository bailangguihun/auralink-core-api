CREATE FUNCTION community.v2_to_canonical_notification() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE post_uuid uuid;
BEGIN
 IF pg_trigger_depth()>1 OR NEW.actor_id IS NULL OR NEW.type NOT IN ('comment','reply','like','adopt','review_request','review_complete') THEN RETURN NEW; END IF;
 IF TG_OP='INSERT' AND EXISTS(SELECT 1 FROM community.v2_notifications WHERE user_id=NEW.user_id AND actor_id=NEW.actor_id AND type=NEW.type AND target_id=NEW.target_id) THEN RETURN NEW; END IF;
 SELECT legacy_id INTO post_uuid FROM community.v2_posts WHERE id=NEW.target_id;
 IF post_uuid IS NULL THEN RETURN NEW; END IF;
 IF NEW.legacy_id IS NULL THEN NEW.legacy_id=gen_random_uuid(); END IF;
 INSERT INTO community.notifications(id,user_id,actor_id,post_id,kind,created_at,read_at)
 VALUES(NEW.legacy_id,NEW.user_id,NEW.actor_id,post_uuid,NEW.type,NEW.create_time::timestamptz,NEW.read_at::timestamptz)
 ON CONFLICT(id) DO UPDATE SET read_at=excluded.read_at;
 IF NEW.read_at IS NOT NULL THEN UPDATE community.notifications SET read_at=NEW.read_at::timestamptz WHERE user_id=NEW.user_id AND actor_id=NEW.actor_id AND post_id=post_uuid AND kind=NEW.type AND read_at IS NULL; END IF;
 RETURN NEW;
END $$;
