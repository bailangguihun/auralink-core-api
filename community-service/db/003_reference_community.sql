CREATE FUNCTION community.canonical_reaction_to_v2() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE pid integer; row community.reactions;
BEGIN
 IF pg_trigger_depth()>1 OR current_setting('artlive.reference_write',true)='on' THEN RETURN coalesce(NEW,OLD); END IF;
 row=CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
 SELECT id INTO pid FROM community.v2_posts WHERE legacy_id=row.post_id;
 IF row.kind='like' THEN
  IF TG_OP='DELETE' THEN DELETE FROM community.v2_post_likes WHERE post_id=pid AND user_id=row.user_id;
  ELSE INSERT INTO community.v2_post_likes(post_id,user_id) VALUES(pid,row.user_id) ON CONFLICT DO NOTHING; END IF;
 ELSE
  IF TG_OP='DELETE' THEN DELETE FROM community.v2_favorites WHERE post_id=pid AND user_id=row.user_id;
  ELSE INSERT INTO community.v2_favorites(post_id,user_id) VALUES(pid,row.user_id) ON CONFLICT DO NOTHING; END IF;
 END IF;
 UPDATE community.v2_posts SET like_count=(SELECT count(*) FROM community.reactions WHERE post_id=row.post_id AND kind='like') WHERE id=pid;
 RETURN coalesce(NEW,OLD);
END $$;
