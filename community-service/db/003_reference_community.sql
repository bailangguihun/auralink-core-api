CREATE FUNCTION community.v2_to_canonical_post() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF pg_trigger_depth()>1 THEN RETURN coalesce(NEW,OLD); END IF;
 IF TG_OP='DELETE' THEN UPDATE community.posts SET status='DELETED',updated_at=now() WHERE id=OLD.legacy_id; RETURN OLD; END IF;
 IF NEW.legacy_id IS NULL THEN NEW.legacy_id=gen_random_uuid(); END IF;
 INSERT INTO community.posts(id,author_id,content,status,created_at,updated_at)
 VALUES(NEW.legacy_id,NEW.user_id,NEW.content,CASE WHEN NEW.status=0 THEN 'ACTIVE' ELSE 'DELETED' END,NEW.create_time::timestamptz,NEW.update_time::timestamptz)
 ON CONFLICT(id) DO UPDATE SET content=excluded.content,status=excluded.status,updated_at=excluded.updated_at;
 RETURN NEW;
END $$;
CREATE TRIGGER v2_post_to_canonical BEFORE INSERT OR UPDATE OR DELETE ON community.v2_posts FOR EACH ROW EXECUTE FUNCTION community.v2_to_canonical_post();
