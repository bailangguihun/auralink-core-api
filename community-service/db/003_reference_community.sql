 SELECT id INTO pid FROM community.v2_posts WHERE legacy_id=NEW.post_id;
 IF pid IS NULL THEN RETURN NEW; END IF;
 INSERT INTO community.v2_notifications(user_id,actor_id,type,target_id,message,read_at,create_time,legacy_id)
 VALUES(NEW.user_id,NEW.actor_id,NEW.kind,pid,CASE NEW.kind WHEN 'like' THEN '赞了你的作品' WHEN 'comment' THEN '评论了你的作品' WHEN 'reply' THEN '回复了你的评论' WHEN 'adopt' THEN '采纳了你的点评' WHEN 'review_request' THEN '邀请你复评作品' ELSE '作品有新的成长动态' END,CASE WHEN NEW.read_at IS NULL THEN NULL ELSE to_char(NEW.read_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') END,to_char(NEW.created_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),NEW.id)
 ON CONFLICT(user_id,actor_id,type,target_id) DO UPDATE SET message=excluded.message,read_at=excluded.read_at,create_time=excluded.create_time;
 RETURN NEW;
END $$;
